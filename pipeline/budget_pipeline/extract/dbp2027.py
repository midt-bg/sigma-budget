def norm(s):
    return re.sub(r"\s+", " ", s).strip()


NUM_RE = re.compile(r"-?\d{1,3}(?: \d{3})+(?:,\d+)?|-?\d+(?:,\d+)?")


def parse_num(tok):
    t = tok.replace("−", "-").replace(" ", "").replace("\xa0", "").replace(",", ".")
    return float(t)


def nums_in(text):
    text = norm(text).replace("−", "-")
    return [parse_num(m.group(0)) for m in NUM_RE.finditer(text)]


def is_num_cell(c):
    return bool(re.fullmatch(r"-?\d{1,3}(?: \d{3})+(?:,\d+)?|-?\d+(?:,\d+)?", c.strip()))


doc = pymupdf.open(str(PDF))
sha = hashlib.sha256(PDF.read_bytes()).hexdigest()
