import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { gazetteFacts, next2027, parliamentFacts } from './law-evidence.js';

const fixture = (name: string) =>
  JSON.parse(readFileSync(resolve(import.meta.dirname, '../../test/fixtures/law', name), 'utf8'));
const evidence = fixture('evidence.json');
const oracle = fixture('parliament-oracle.json');
const ids: Record<string, number> = { zdb: 167157, zbdoo: 167156, zbnzok: 167155 };

describe('law evidence', () => {
  it('matches Parliament facts independently generated by Python', () => {
    for (const key of Object.keys(ids))
      expect(parliamentFacts(ids[key]!, evidence.parliament[key])).toEqual(oracle[key]);
  });
  it('rejects changed reading stages and missing proposal files', () => {
    const changed = structuredClone(evidence.parliament.zdb);
    for (const activity of changed.activity)
      if (activity.L_Act_St2_name === 'зала първо гласуване')
        activity.L_Act_St2_name = 'неизвестен етап';
    expect(() => parliamentFacts(ids.zdb!, changed)).toThrow();
    const missing = structuredClone(evidence.parliament.zdb);
    missing.proposal_12_list[0].act_files = [];
    expect(() => parliamentFacts(ids.zdb!, missing)).toThrow();
  });
  it('matches facts derived from the Python parser blocks', () => {
    const expected = fixture('gazette-oracle.json');
    for (const key of Object.keys(ids))
      expect(gazetteFacts(evidence.dvBlocks[key])).toEqual(expected[key]);
    expect(() => gazetteFacts([])).toThrow();
  });
  it('consumes explicit literal data decoded by Python and rejects raw literals', () => {
    const data = structuredClone(evidence.parliament.zdb);
    const literal = fixture('literal-data.json')[0];
    data.proposal_12_list[0].act_files = literal.expected;
    expect(
      parliamentFacts(ids.zdb!, data).proposals.some(
        (p: { file: string }) => p.file === 'proposal.pdf',
      ),
    ).toBe(true);
    data.proposal_12_list[0].act_files = literal.text;
    expect(() => parliamentFacts(ids.zdb!, data)).toThrow();
  });
  it('isolates the frozen 2027 wording', () =>
    expect(next2027()).toEqual(fixture('next2027.json')));
});

it('retains the pinned fixture bytes', async () => {
  const { createHash } = await import('node:crypto');
  const provenance = fixture('provenance.json');
  for (const [name, hash] of Object.entries(provenance.fixtureSha256)) {
    const bytes = readFileSync(resolve(import.meta.dirname, '../../test/fixtures/law', name));
    expect(createHash('sha256').update(bytes).digest('hex')).toBe(hash);
  }
});
