/** MuPDF producer, independently checked against the PDFMiner source transcription.
 * Python tests regenerate the shared reference from these exact pinned bytes.
 */
export function verifyProgrammeSource(source: ProgrammeSource, bytes: Uint8Array) {
  const reference = programmeReferences[source.code];
  if (
    !reference ||
    createHash('sha256').update(bytes).digest('hex') !== reference.sourceSha256 ||
    !programmeEqual(source, reference)
  )
    throw new Error('Programme cells differ from independent PDFMiner source transcription');
}
export function readProductionProgrammes(context: Readonly<ExecutionContext>) {
  return supplementaryProgrammeCodes.map((code) => {
    const reference = programmeReferences[code]!,
      path = 'data/originals/program_budgets/' + reference.file,
      inputs = context.inputs.filter((i) => i.path === path),
      generated = context.generatedIntermediates?.filter((i) => i.path === path) ?? [],
      declarations = context.missingIntermediates?.filter((i) => i.path === path) ?? [];
    // Reproducible PDF members may be absent from the raw-input snapshot. The
    // loader authenticates their archive extraction against the committed pin;
    // entry.ts then records the actual generated bytes before this reader runs.
    const directPin =
        inputs.length === 1 &&
        generated.length === 0 &&
        declarations.length === 0 &&
        inputs[0]!.sha256 === reference.sourceSha256,
      generatedPin =
        inputs.length === 0 &&
        generated.length === 1 &&
        declarations.length === 1 &&
        declarations[0]!.declaration === 'data/originals/program_budgets/*' &&
        declarations[0]!.legacyPin === reference.sourceSha256 &&
        generated[0]!.kind === 'generated-intermediate' &&
        generated[0]!.sha256 === reference.sourceSha256;
    if (!directPin && !generatedPin) throw new Error('Missing programme source pin: ' + path);
    const bytes = readFileSync(join(context.preparedInputRoot ?? context.exportRoot, path));
    const { positions: _, ...decoded } = readProgrammeSupplement(
      bytes,
      code as keyof typeof programmeLayouts,
    );
    const source = { ...decoded, file: reference.file };
    verifyProgrammeSource(source, bytes);
    return source;
  });
}
const programmeSourceNote =
  'Програмни таблици от архива към законопроекта за държавния бюджет. Означенията на годините са запазени от документите; съпоставката с приетия закон е отделна.';
export function supplementBudgetFiles(base: Record<string, any>, sources: ProgrammeSource[]) {
  if (!programmeEqual(sources.map((s) => s.code).sort(), supplementaryProgrammeCodes))
    throw new Error('Incomplete/duplicate programme supplements');
  const out = { ...base },
    ministries = structuredClone(base['ministries.json']),
    index = structuredClone(base['programs.json']);
  for (const source of sources) {
    if (!programmeEqual(source, programmeReferences[source.code]))
      throw new Error('Changed programme source cells');
    const item = ministries.items.find((i: any) => i.id === source.code);
    if (item?.programs.status !== 'pending' || out[`ministries/${source.code}.json`])
      throw new Error('Programme supplement must replace a pending agency');
    const { total, policies } = programmeProjection(source),
      accounting = programmeAccounting(source),
      notes = programmeNotes(source),
      pages = [...new Set(source.rows.map((r) => r.page))];
    const template = base['ministries/0200.json'];
    const doc = {
      meta: {
        ...template.meta,
        title: 'Програмен бюджет: ' + item.name,
        sourceNote: programmeSourceNote,
      },
      id: item.id,
      art: item.art,
      name: item.name,
      short: item.short,
      tier: 'source-verified',
      years: template.years,
      yearLabels: programmeYearLabels(source.code),
      vintage: programmeVintage(source.code),
      cols: programmeColumns,
      policiesKind: item.policiesKind,
      total,
      policies,
      yearsComplete: [2026],
      check: {
        prbTotal2026: source.rows[0]!.values[1],
        zdbExp: item.expKhil,
        matchesLaw: item.expKhil === source.rows[0]!.values[1],
        sourceDifferences: Object.keys(accounting.differences).length,
        unavailableChecks: accounting.unavailable.length,
      },
      skipped: [],
      skippedTotal: 0,
      doc: {
        file: source.file,
        pages,
        pagesByYear: { '2026': pages },
        archive: template.doc.archive,
        archiveUrl: template.doc.archiveUrl,
      },
      sourceContract: 'programme-supplement/1',
      sourceAudit: { sourceSha256: source.sourceSha256, rows: source.rows },
      accounting,
      notes,
    };
    if (!programmeSupplementGuard(doc))
      throw new Error('Invalid programme supplement ' + source.code);
    out[`ministries/${source.code}.json`] = doc;
    const all = policies.flatMap((p) =>
      p.kind === 'policy'
        ? [
            { node: p, level: 'policy', parent: '' },
            ...p.programs.map((q: any) => ({ node: q, level: 'program', parent: p.code })),
          ]
        : [{ node: p, level: 'program', parent: '' }],
    );
    const programCount = all.filter((r) => r.level === 'program').length,
      policyCount = all.filter((r) => r.level === 'policy').length;
    item.programs = {
      status: 'real',
      tier: 'source-verified',
      matchesLaw: doc.check.matchesLaw,
      count: programCount,
      policyCount,
      file: `ministries/${source.code}.json`,
      notes,
    };
    if (!doc.check.matchesLaw) ministries.programTotals.differ++;
    ministries.programTotals.budgets++;
    ministries.programTotals.pending--;
    ministries.programTotals.programs += programCount;
    ministries.programTotals.policies += policyCount;
    for (const { node, level, parent } of all)
      index.items.push([
        source.code,
        node.code,
        node.name,
        level,
        parent,
        node.values['2026'][0],
        -1,
        -101,
        0,
        node.values['2026'][1],
        -1,
      ]);
  }
  ministries.tiers['source-verified'] =
    'Проверени редове от оригиналния документ; разликите в сборовете са описани';
  delete ministries.tiers.pending;
  index.meta.sourceNote = programmeSourceNote;
  out['ministries.json'] = ministries;
  out['programs.json'] = index;
  return out;
}
export function withProductionProgrammes(
  stages: readonly GraphStage[],
  sources: ProgrammeSource[],
): GraphStage[] {
  return stages.map((stage) =>
    stage.id === 'budgets'
      ? {
          ...stage,
          run: (read: (id: string) => unknown) =>
            supplementBudgetFiles(stage.run(read) as Record<string, any>, sources),
        }
      : stage.id === 'search'
        ? {
            ...stage,
            run: (read: (id: string) => any) => {
              const budgets = read('budgets'),
                index = budgets['programs.json'];
              const withoutProgrammes = { ...budgets, 'programs.json': { ...index, items: [] } };
              const base = stage.run((id) => (id === 'budgets' ? withoutProgrammes : read(id)));
              return compactProgrammeSearch(base, index, budgets['ministries.json']);
            },
          }
        : stage.id === 'catalog'
          ? {
              ...stage,
              run: (read: (id: string) => unknown) => reviseProgrammeCatalog(stage.run(read)),
            }
          : stage,
  );
}

/** Independent validation consumes only the published contract, source bytes and PDFMiner proof. */
export function verifyPublishedProgrammes(document: unknown, sourcePath: string): void {
  if (!programmeSupplementGuard(document))
    throw new Error('Invalid independent programme cell contract');
  const reference = programmeReferences[document.id]!;
  if (
    createHash('sha256').update(readFileSync(sourcePath)).digest('hex') !== reference.sourceSha256
  )
    throw new Error('Programme validation source pin');
}
